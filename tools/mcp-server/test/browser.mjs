import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fixture, root } from './helpers.mjs';
import { Runner, contrast } from '../build/index.js';

const { workspace, generated } = await fixture('admin-validation', { mode: 'application', title: 'SQ Workspace', theme: { brand: '#00c474' } });
const runner = new Runner(workspace);
const controller = new AbortController();
let browser;
try {
  const build = await runner.validate(generated.artifactId, controller.signal);
  if (build.status !== 'passed') console.error(JSON.stringify(build, null, 2));
  assert.equal(build.status, 'passed', 'Generated admin must pass typecheck and production build');
  const preview = await runner.preview(generated.artifactId, { widths: [320, 390, 768, 1440], modes: ['light', 'dark'], engine: 'chromium', routes: ['dashboard', 'users', 'settings'] }, controller.signal);
  browser = await chromium.launch({ executablePath: process.env.SQ_UI_BROWSER, headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  await page.goto(preview.previewUrl + '/#/users');
  await page.getByRole('heading', { name: 'Users', exact: true }).waitFor();
  const rowSelector = 'tr[data-user-id]';
  await page.locator(rowSelector).first().waitFor();
  assert.equal(await page.locator(rowSelector).count(), 5);
  const pageOne = await page.locator(rowSelector).first().getAttribute('data-user-id');
  await page.getByRole('button', { name: 'Next page', exact: true }).click();
  await page.waitForFunction(previous => document.querySelector('tr[data-user-id]')?.getAttribute('data-user-id') !== previous, pageOne);
  await page.getByRole('button', { name: 'First page', exact: true }).click();
  const search = page.getByRole('textbox', { name: 'Search users' });
  await search.fill('no matching person');
  await page.getByRole('heading', { name: 'No users found' }).waitFor();
  await search.fill('');
  await page.getByLabel('Status', { exact: true }).selectOption('inactive');
  await page.waitForFunction(() => [...document.querySelectorAll('tr[data-user-id]')].every(row => row.textContent.includes('Inactive')));
  await page.getByLabel('Status', { exact: true }).selectOption('all');
  const first = await page.locator(rowSelector).first().getAttribute('data-user-id');
  await page.getByLabel('Sort by name', { exact: true }).selectOption('name-desc');
  await page.waitForFunction(previous => document.querySelector('tr[data-user-id]')?.getAttribute('data-user-id') !== previous, first);
  await page.getByRole('link', { name: 'Add user', exact: true }).click();
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  await page.getByText('This field is required.', { exact: true }).waitFor();
  await page.getByRole('textbox', { name: 'Name', exact: true }).fill('MCP Generated User');
  await page.getByRole('textbox', { name: 'Email', exact: true }).fill('generated@example.com');
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  await page.getByRole('heading', { name: 'Users', exact: true }).waitFor();
  await page.getByRole('textbox', { name: 'Search users' }).fill('MCP Generated User');
  await page.getByRole('link', { name: 'Edit MCP Generated User', exact: true }).click();
  await page.getByRole('textbox', { name: 'Name', exact: true }).fill('MCP Edited User');
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  await page.getByRole('textbox', { name: 'Search users' }).fill('MCP Edited User');
  const deletion = page.getByRole('button', { name: 'Delete MCP Edited User', exact: true });
  await deletion.click();
  await page.getByRole('dialog').waitFor();
  assert.equal(await page.evaluate(() => document.body.style.overflow), 'hidden');
  await page.keyboard.press('Escape');
  await page.waitForFunction(() => !document.querySelector('[role="dialog"]')?.closest('[inert]') ? false : true);
  assert.equal(await deletion.count(), 1);
  assert.equal(await deletion.evaluate(element => element === document.activeElement), true);
  await deletion.click();
  await page.getByRole('button', { name: 'Confirm deletion', exact: true }).click();
  await page.getByRole('heading', { name: 'No users found' }).waitFor();
  await search.fill('');
  await page.getByRole('button', { name: 'Show error state', exact: true }).click();
  await page.getByRole('alert').waitFor();
  await page.getByRole('button', { name: 'Try again', exact: true }).click();
  await page.locator(rowSelector).first().waitFor();
  await page.getByRole('link', { name: 'Settings', exact: true }).click();
  await page.getByRole('textbox', { name: 'Name', exact: true }).fill('Saved workspace');
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Changes saved.' }).waitFor();
  await page.getByLabel('Theme', { exact: true }).selectOption('dark');
  await page.waitForFunction(() => document.documentElement.dataset.sqTheme === 'dark');
  const usersLink = page.getByRole('link', { name: 'Users', exact: true });
  await usersLink.hover();
  const colors = await usersLink.evaluate(element => [getComputedStyle(element).color, getComputedStyle(element.closest('aside')).backgroundColor]);
  const asHex = value => '#' + value.match(/\d+/g).slice(0, 3).map(part => Number(part).toString(16).padStart(2, '0')).join('');
  assert.ok(contrast(asHex(colors[0]), asHex(colors[1])) >= 4.5, 'Hovered links remain readable in the dark theme');
  await page.reload();
  await page.waitForFunction(() => document.documentElement.dataset.sqTheme === 'dark');
  await page.setViewportSize({ width: 390, height: 900 });
  await page.getByRole('button', { name: 'Menu', exact: true }).click();
  await page.getByRole('link', { name: 'Dashboard', exact: true }).click();
  await page.getByRole('heading', { name: 'Dashboard', exact: true }).waitFor();
  await writeFile(path.join(root, '.sq-ui-mcp/reports/admin-interactions.json'), JSON.stringify({ status: 'passed', checks: ['search and empty state', 'status filter', 'sorting', 'required validation', 'create and edit shared records', 'cancel deletion with Escape', 'confirm deletion', 'error and retry', 'settings save', 'theme persistence', 'mobile navigation'] }, null, 2));
  if (preview.status !== 'passed') console.error(JSON.stringify(preview.checks.filter(check => check.status !== 'passed'), null, 2));
  assert.equal(preview.status, 'passed', 'Generated pages must pass runtime, overflow and axe checks');
  console.log(`Admin production build, 24 viewport/theme/page checks and CRUD/form/navigation interactions passed. Screenshots: .sq-ui-mcp/screenshots/${generated.artifactId}`);
} finally { await browser?.close(); runner.close(); }
